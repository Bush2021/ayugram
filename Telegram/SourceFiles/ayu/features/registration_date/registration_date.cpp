Estimate EstimateForUser(uint64 userId) {
	const auto first = std::begin(kAnchors);
	const auto last = std::end(kAnchors) - 1;
	if (userId < first->id) {
		return { Bound::Before, first->date };
	} else if (userId > last->id) {
		return { Bound::After, last->date };
	}
	const auto after = std::lower_bound(
		first,
		std::end(kAnchors),
		userId,
		[](const Anchor &anchor, uint64 id) { return anchor.id < id; });
	if (after->id == userId) {
		return { Bound::Around, after->date };
	}
	const auto before = after - 1;
	const auto ratio = double(userId - before->id)
		/ double(after->id - before->id);
	const auto offset = std::llround(ratio * (after->date - before->date));
	return { Bound::Around, before->date + TimeId(offset) };
}

